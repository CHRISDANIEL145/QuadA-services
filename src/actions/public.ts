// SUBMIT CONTACT MESSAGE
// Public action
// ============================================================
export async function submitContactMessage(
  formData: unknown
): Promise<ActionResult> {
  try {
    const parsed = contactSchema.safeParse(formData)
    if (!parsed.success) {
      const fieldErrors: Record<string, string[]> = {}
      for (const issue of parsed.error.issues) {
        const field = issue.path[0] as string
        if (!fieldErrors[field]) fieldErrors[field] = []
        fieldErrors[field].push(issue.message)
      }
      return { success: false, error: 'Validation failed', fieldErrors }
    }

    const data = parsed.data
    const supabase = await createClient()

    const { error } = await supabase.from('contact_messages').insert({
      name: data.name,
      email: data.email,
      phone: data.phone || null,
      message: data.message,
    })

    if (error) {
      console.error('Contact message error:', error)
      return { success: false, error: 'Could not send message. Please try again.' }
    }

    return { success: true }
  } catch (err) {
    console.error('submitContactMessage error:', err)
    return { success: false, error: 'An unexpected error occurred.' }
  }
}

// ============================================================
// GET PUBLIC SERVICES (with categories)
// ============================================================
export async function getPublicServices() {
  const supabase = await createClient()
  const { data, error } = await supabase
    .from('services')
    .select(`
      *,
      service_categories!inner(*)
    `)
    .eq('is_active', true)
    .eq('service_categories.is_active', true)
    .order('sort_order', { ascending: true })

  if (error) {
    console.error('getPublicServices error:', error)
    return []
  }
  return data || []
}

